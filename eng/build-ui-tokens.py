#!/usr/bin/env python3
"""Build the application's shared token adapters, or verify committed output with --check."""
from __future__ import annotations

import argparse
import json
import math
from pathlib import Path
import re
import sys
from xml.sax.saxutils import escape

ROOT = Path(__file__).resolve().parent.parent
SOURCE = ROOT / "apps/design/tokens.json"


def resolve_tokens(document: dict) -> dict[str, tuple[str, object]]:
    tokens = {}

    def collect(node, prefix="", depth=0):
        if not isinstance(node, dict) or depth > 12:
            raise ValueError("Token groups must be objects within the supported depth.")
        if "$value" in node:
            tokens[prefix] = node
            return
        for key, child in node.items():
            if key.startswith("$"):
                continue
            if not re.fullmatch(r"[a-zA-Z0-9]+", key):
                raise ValueError("Token names must use letters or digits.")
            collect(child, f"{prefix}.{key}" if prefix else key, depth + 1)

    collect(document)
    if not tokens or len(tokens) > 256:
        raise ValueError("Expected between 1 and 256 application tokens.")
    resolved = {}

    def resolve(name, stack):
        if name in resolved:
            return resolved[name]
        if name not in tokens or name in stack:
            raise ValueError(f"Missing or cyclic token alias: {name}")
        token = tokens[name]
        kind, value = token.get("$type"), token["$value"]
        if isinstance(value, str) and value.startswith("{") and value.endswith("}"):
            alias_kind, value = resolve(value[1:-1], stack | {name})
            if kind != alias_kind:
                raise ValueError(f"Token alias types differ: {name}")
        if kind == "color":
            if not isinstance(value, str) or not re.fullmatch(r"#[0-9a-fA-F]{6}", value):
                raise ValueError(f"Expected an opaque RGB color: {name}")
        elif kind == "dimension":
            if not isinstance(value, dict) or set(value) != {"value", "unit"} or value["unit"] != "px":
                raise ValueError(f"Expected a pixel dimension: {name}")
            number = value["value"]
            if type(number) not in (float, int) or not math.isfinite(number) or not 0 <= number <= 4096:
                raise ValueError(f"Invalid dimension: {name}")
        elif kind == "number":
            if type(value) not in (float, int) or not math.isfinite(value) or not 0 <= value <= 100:
                raise ValueError(f"Invalid number: {name}")
        else:
            raise ValueError(f"Unsupported application token type: {name}")
        resolved[name] = (kind, value)
        return resolved[name]

    for name in tokens:
        resolve(name, set())
    return resolved


def generate(tokens, stylesheet):
    css = ["/* Generated by eng/build-ui-tokens.py. Edit apps/design/tokens.json. */", ":root {"]
    native = ['<!-- Generated by eng/build-ui-tokens.py. Edit apps/design/tokens.json. -->',
              '<ResourceDictionary xmlns="https://github.com/avaloniaui" xmlns:x="http://schemas.microsoft.com/winfx/2006/xaml">']
    for name, (kind, value) in tokens.items():
        key = ".".join(part[0].upper() + part[1:] for part in name.split("."))
        if kind == "color":
            css.append(f"    --{name.replace('.', '-')}: {value};")
            native.append(f'  <SolidColorBrush x:Key="{key}">{escape(value)}</SolidColorBrush>')
            native.append(f'  <Color x:Key="{key}.Value">{escape(value)}</Color>')
        else:
            number = value["value"] if kind == "dimension" else value
            text = f"{number:g}"
            css.append(f"    --{name.replace('.', '-')}: {text}{'px' if kind == 'dimension' else ''};")
            native.append(f'  <x:Double x:Key="{key}">{text}</x:Double>')
            if name.startswith(("space.", "border.")):
                native.append(f'  <Thickness x:Key="{key}.Inset">{text}</Thickness>')
                native.append(f'  <Thickness x:Key="{key}.Horizontal">{text},0</Thickness>')
                native.append(f'  <Thickness x:Key="{key}.Vertical">0,{text}</Thickness>')
                native.append(f'  <Thickness x:Key="{key}.Bottom">0,0,0,{text}</Thickness>')
            if name.startswith("radius."):
                native.append(f'  <CornerRadius x:Key="{key}.Corners">{text}</CornerRadius>')
            if name == "size.panel":
                native.append(f'  <GridLength x:Key="{key}.Column">{text}</GridLength>')
    css.extend(["}", ""])
    native.extend(["</ResourceDictionary>", ""])

    def dimension(match):
        kind, value = tokens[match[1]]
        if kind != "dimension":
            raise ValueError("CSS media adapters require dimensions.")
        return f'{value["value"]:g}px'

    stylesheet = re.sub(r"\{\{([a-zA-Z0-9.]+)\}\}", dimension, stylesheet)
    return {
        ROOT / "apps/web/Application.Web/wwwroot/tokens.css": "\n".join(css),
        ROOT / "apps/web/Application.Web/wwwroot/app.css": "/* Generated from apps/design/web.css. */\n" + stylesheet,
        ROOT / "apps/desktop/workstation/Application.Workstation/Styles/DesignTokens.axaml": "\n".join(native),
    }


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    if SOURCE.stat().st_size > 1024 * 1024:
        raise ValueError("Application token input exceeds 1 MiB.")
    tokens = resolve_tokens(json.loads(SOURCE.read_text()))
    outputs = generate(tokens, (ROOT / "apps/design/web.css").read_text())
    for path, value in outputs.items():
        if args.check:
            if not path.exists() or path.read_text() != value:
                print(f"Generated UI output differs: {path.relative_to(ROOT)}. Run python3 eng/build-ui-tokens.py.")
                return 1
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(value)
    print(f"{'Verified' if args.check else 'Generated'} {len(tokens)} application tokens for Web and Workstation.")
    return 0


if __name__ == "__main__":
    try:
        sys.exit(main())
    except (ValueError, KeyError, OSError) as error:
        print(f"UI token build failed: {error}", file=sys.stderr)
        sys.exit(1)
